"""Check the research documents' citations and render the reference list.

* every ``[@key]`` / ``@key`` citation in docs/research/survey.md and docs/research/systems/*.md must
  exist in research/papers/index.yaml;
* writes docs/research/references.md: a numbered list of every cited source with its canonical
  title (arXiv metadata from research/papers/metadata.json) and link, grouped by role.

    uv run python scripts/check_citations.py      # exit 1 on unknown keys
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "research" / "papers" / "index.yaml"
META = ROOT / "research" / "papers" / "metadata.json"
DOCS = [
    ROOT / "docs" / "research" / "survey.md",
    ROOT / "docs" / "research" / "README.md",
    *sorted((ROOT / "docs" / "research" / "systems").glob("*.md")),
]
OUT = ROOT / "docs" / "research" / "references.md"
CITE = re.compile(r"\[(@[^\]]+)\]")
KEY = re.compile(r"@([a-z0-9][a-z0-9-]*)")
ROLE_TITLES = {
    "implementation": "System One implementations",
    "benchmark": "Evaluations and benchmarks",
    "dataset": "Datasets",
    "product": "Hosted products and documentation",
    "background": "Background and foundations",
}


def cited_keys(text: str) -> list[str]:
    keys: list[str] = []
    for group in CITE.findall(text):
        keys += KEY.findall(group)
    return keys


def main() -> int:
    index = yaml.safe_load(INDEX.read_text(encoding="utf-8"))
    meta = json.loads(META.read_text(encoding="utf-8")) if META.exists() else {}
    entries = {e["key"]: {**e, "kind": "arxiv"} for e in index["arxiv"]}
    entries.update({e["key"]: {**e, "kind": "link"} for e in index["links"]})

    usage: dict[str, set[str]] = {}
    unknown: list[str] = []
    for doc in DOCS:
        if not doc.exists():
            continue
        for key in cited_keys(doc.read_text(encoding="utf-8")):
            if key not in entries:
                unknown.append(f"{doc.relative_to(ROOT)}: @{key}")
            else:
                usage.setdefault(key, set()).add(doc.stem)

    lines = [
        "# References",
        "",
        "Generated by `scripts/check_citations.py` from `research/papers/index.yaml`; titles of arXiv "
        "papers are the canonical ones returned by the arXiv API. *Cited in* lists the documents that "
        "use each source.",
        "",
    ]
    n = 0
    for role, heading in ROLE_TITLES.items():
        keys = sorted(k for k in usage if entries[k]["role"] == role)
        if not keys:
            continue
        lines += [f"## {heading}", ""]
        for k in keys:
            n += 1
            e = entries[k]
            where = ", ".join(sorted(usage[k]))
            if e["kind"] == "arxiv":
                m = meta.get(e["id"], {})
                authors = m.get("authors", [])
                who = f"{authors[0]} et al." if len(authors) > 2 else " & ".join(authors)
                title = m.get("title", e["system"])
                lines.append(
                    f"{n}. **[{k}]** {who} *{title}*. arXiv:{e['id']} ({m.get('published', '')[:4]}). "
                    f"<https://arxiv.org/abs/{e['id']}> — cited in: {where}"
                )
            else:
                lines.append(f"{n}. **[{k}]** *{e['title']}*. <{e['url']}> — cited in: {where}")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")

    print(
        f"{len(usage)} distinct sources cited across {sum(d.exists() for d in DOCS)} documents -> {OUT.name}"
    )
    for u in unknown:
        print("UNKNOWN CITATION:", u)
    return 1 if unknown else 0


if __name__ == "__main__":
    sys.exit(main())
