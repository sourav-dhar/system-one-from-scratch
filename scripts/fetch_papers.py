"""Build the local research library from research/papers/index.yaml.

For every arXiv entry this fetches the canonical metadata (title, authors, date) from the arXiv API and
the licence from the abstract page, then downloads the PDF into research/papers/pdf/ (gitignored: many
papers carry arXiv's non-exclusive licence, which does not permit redistribution). It writes:

* research/papers/metadata.json - cached metadata (committed; lets the bibliography build offline);
* research/papers/MANIFEST.md   - one row per paper: key, title, date, licence, redistributable, sha256;
* docs/research/survey.bib      - BibTeX for the survey, arXiv papers plus link-only sources.

    uv run python scripts/fetch_papers.py            # metadata + PDFs (idempotent)
    uv run python scripts/fetch_papers.py --no-pdf   # metadata and bibliography only
    uv run python scripts/fetch_papers.py --refresh  # re-query arXiv even if cached

arXiv asks API clients to wait about 3 s between requests; this script does.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "research" / "papers" / "index.yaml"
PDF_DIR = ROOT / "research" / "papers" / "pdf"
META = ROOT / "research" / "papers" / "metadata.json"
MANIFEST = ROOT / "research" / "papers" / "MANIFEST.md"
BIB = ROOT / "docs" / "research" / "survey.bib"
USER_AGENT = "systemone-research-fetcher/0.1 (research library builder)"
DELAY_S = 3.0
ATOM = "{http://www.w3.org/2005/Atom}"
REDISTRIBUTABLE = (
    "creativecommons.org/licenses/by/",
    "creativecommons.org/licenses/by-sa/",
    "creativecommons.org/publicdomain/zero/",
)


def get(url: str, timeout: float = 60.0) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data: bytes = r.read()
        return data


def load_index() -> dict[str, list[dict[str, Any]]]:
    data: dict[str, list[dict[str, Any]]] = yaml.safe_load(INDEX.read_text(encoding="utf-8"))
    return data


def arxiv_metadata(ids: list[str]) -> dict[str, dict[str, Any]]:
    """Title, authors and first-version date for each id, in batches of 50."""
    out: dict[str, dict[str, Any]] = {}
    for i in range(0, len(ids), 50):
        batch = ids[i : i + 50]
        url = f"https://export.arxiv.org/api/query?id_list={','.join(batch)}&max_results={len(batch)}"
        root = ET.fromstring(get(url))
        for entry in root.findall(f"{ATOM}entry"):
            raw_id = entry.findtext(f"{ATOM}id", "")
            m = re.search(r"abs/(\d{4}\.\d{4,5})", raw_id)
            if not m:
                continue
            title = " ".join((entry.findtext(f"{ATOM}title") or "").split())
            out[m.group(1)] = {
                "title": title,
                "authors": [a.findtext(f"{ATOM}name", "").strip() for a in entry.findall(f"{ATOM}author")],
                "published": (entry.findtext(f"{ATOM}published") or "")[:10],
            }
        time.sleep(DELAY_S)
    return out


def arxiv_license(arxiv_id: str) -> str:
    html = get(f"https://arxiv.org/abs/{arxiv_id}").decode("utf-8", "replace")
    m = re.search(
        r'href="(https?://(?:creativecommons\.org/(?:licenses|publicdomain)/[^"]+|arxiv\.org/licenses/[^"]+))"',
        html,
    )
    return m.group(1) if m else "unknown"


def licence_label(licence: str) -> str:
    """'https://creativecommons.org/licenses/by-sa/4.0/' -> 'by-sa 4.0'; arXiv's -> 'nonexclusive-distrib'."""
    parts = licence.rstrip("/").split("/")
    if "creativecommons.org" in licence and len(parts) >= 2:
        return f"CC {parts[-2]} {parts[-1]}"
    return parts[-2] if len(parts) >= 2 and "arxiv.org" in licence else licence


def is_redistributable(licence: str) -> bool:
    return any(s in licence for s in REDISTRIBUTABLE)


def download_pdf(arxiv_id: str, dst: Path) -> str:
    """Download unless already present and valid. Returns the sha256."""
    if not (dst.exists() and dst.read_bytes()[:4] == b"%PDF"):
        data = get(f"https://arxiv.org/pdf/{arxiv_id}", timeout=120.0)
        if data[:4] != b"%PDF":
            raise ValueError(f"{arxiv_id}: response is not a PDF")
        dst.write_bytes(data)
        time.sleep(DELAY_S)
    return hashlib.sha256(dst.read_bytes()).hexdigest()


def bib_escape(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def write_bib(
    arxiv: list[dict[str, Any]], links: list[dict[str, Any]], meta: dict[str, dict[str, Any]]
) -> None:
    lines = [
        "% Generated by scripts/fetch_papers.py from research/papers/index.yaml - do not edit by hand.",
        "",
    ]
    for e in arxiv:
        m = meta.get(e["id"])
        if not m:
            continue
        lines += [
            f"@misc{{{e['key']},",
            f"  title         = {{{{{bib_escape(m['title'])}}}}},",
            f"  author        = {{{' and '.join(bib_escape(a) for a in m['authors'])}}},",
            f"  year          = {{{m['published'][:4]}}},",
            f"  eprint        = {{{e['id']}}},",
            "  archivePrefix = {arXiv},",
            f"  url           = {{https://arxiv.org/abs/{e['id']}}},",
            f"  note          = {{System: {bib_escape(e['system'])}}},",
            "}",
            "",
        ]
    for e in links:
        lines += [
            f"@misc{{{e['key']},",
            f"  title        = {{{{{bib_escape(e['title'])}}}}},",
            f"  howpublished = {{\\url{{{e['url']}}}}},",
            f"  note         = {{System: {bib_escape(e['system'])}. Accessed 2026-11-21}},",
            "}",
            "",
        ]
    BIB.parent.mkdir(parents=True, exist_ok=True)
    BIB.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-pdf", action="store_true", help="skip PDF downloads")
    ap.add_argument("--refresh", action="store_true", help="re-query arXiv metadata and licences")
    args = ap.parse_args(argv)

    index = load_index()
    arxiv, links = index["arxiv"], index["links"]
    meta: dict[str, dict[str, Any]] = (
        {} if args.refresh or not META.exists() else json.loads(META.read_text())
    )

    missing = [e["id"] for e in arxiv if e["id"] not in meta]
    if missing:
        print(f"querying arXiv for {len(missing)} entries", flush=True)
        for arxiv_id, m in arxiv_metadata(missing).items():
            meta[arxiv_id] = m
    for e in arxiv:
        m = meta.get(e["id"])
        if m is not None and "license" not in m:
            m["license"] = arxiv_license(e["id"])
            time.sleep(DELAY_S)

    problems = []
    for e in arxiv:
        m = meta.get(e["id"])
        if m is None:
            problems.append(f"{e['key']}: {e['id']} not found on arXiv")
        elif e["expect"].lower() not in m["title"].lower():
            problems.append(f"{e['key']}: title {m['title']!r} does not contain {e['expect']!r}")

    META.write_text(
        json.dumps(dict(sorted(meta.items())), indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    rows = []
    if not args.no_pdf:
        PDF_DIR.mkdir(parents=True, exist_ok=True)
    for e in arxiv:
        m = meta.get(e["id"])
        if m is None:
            continue
        sha = ""
        if not args.no_pdf:
            try:
                sha = download_pdf(e["id"], PDF_DIR / f"{e['key']}.pdf")
            except Exception as exc:  # report and continue with the rest
                problems.append(f"{e['key']}: PDF download failed ({exc})")
        lic = m.get("license", "unknown")
        link = f"[{e['id']}](https://arxiv.org/abs/{e['id']})"
        rows.append(
            f"| `{e['key']}` | {link} | {m['title']} | {m['published']} | {e['family']} | "
            f"{licence_label(lic)} | {'yes' if is_redistributable(lic) else 'no'} | {sha[:12]} |"
        )
    MANIFEST.write_text(
        "# Paper manifest\n\nGenerated by `scripts/fetch_papers.py`. PDFs live in `research/papers/pdf/` "
        "(gitignored). *Redistributable* means CC BY, CC BY-SA or CC0; everything else is link-only.\n\n"
        "| Key | arXiv | Title | Date | Family | Licence | Redistributable | sha256 |\n"
        "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n",
        encoding="utf-8",
    )
    write_bib(arxiv, links, meta)

    print(
        f"{len(rows)} arXiv papers, {len(links)} link-only sources; bibliography -> {BIB.relative_to(ROOT)}"
    )
    for p in problems:
        print("WARNING:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
